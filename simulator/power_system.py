    # -- accessors --------------------------------------------------------

    def get_asset(self, asset_id: str) -> AssetData | None:
        """Return a specific asset, or None."""
        return self.assets.get(asset_id)

    def get_all_assets(self) -> list[AssetData]:
        """Return all assets."""
        return list(self.assets.values())

    def get_telemetry_history(self, asset_id: str, max_points: int = 100) -> list[TelemetryData]:
        """Return recent telemetry history for an asset (most recent last)."""
        history = self.telemetry_history.get(asset_id, [])
        return history[-max_points:]

    # -- interventions ----------------------------------------------------

    def inject_failure(self, asset_id: str, failure_type: str) -> bool:
        """Inject a developing fault into an asset.

        Applies an immediate health penalty and activates a persistent failure
        signature that biases sensors and accelerates wear until maintenance.

        Args:
            asset_id: Target asset.
            failure_type: One of ``FAILURE_SIGNATURES``.

        Returns:
            True if the failure was injected.
        """
        asset = self.assets.get(asset_id)
        if asset is None or failure_type not in FAILURE_SIGNATURES:
            return False

        signature = FAILURE_SIGNATURES[failure_type]
        asset.true_health = max(0.0, asset.true_health - signature.health_impact)
        asset.failure_mode = failure_type
        # The fault develops over subsequent ticks as sensors ramp; state will
        # follow the estimated health on the next tick.
        self._update_operating_state(asset)
        return True

    def perform_maintenance(self, asset_id: str) -> bool:
        """Restore an asset's health and clear any active fault.

        Args:
            asset_id: Target asset.

        Returns:
            True if maintenance was performed.
        """
        asset = self.assets.get(asset_id)
        if asset is None:
            return False

        if asset.operating_state == AssetOperationalState.FAILED:
            asset.true_health = 75.0  # rebuild after failure — partial restoration
        else:
            asset.true_health = min(100.0, asset.true_health + 45.0)

        asset.failure_mode = None
        asset.last_maintenance = datetime.now()
        # Fault cleared: sensors now read healthy, so snap the estimate up to the
        # restored condition rather than waiting for the EMA to catch up.
        asset.estimated_health = asset.true_health
        self._update_operating_state(asset)
        return True

    def set_under_maintenance(self, asset_id: str, active: bool) -> bool:
        """Flag/unflag an asset as physically under maintenance (paused wear)."""
        asset = self.assets.get(asset_id)
        if asset is None:
            return False
        if active:
            asset.operating_state = AssetOperationalState.UNDER_MAINTENANCE
        else:
            self._update_operating_state(asset)
        return True

    def _update_operating_state(self, asset: AssetData) -> None:
        """Derive operating state from the *observed* (estimated) health.

        Using the sensor estimate — not the latent truth — keeps the status
        badge, health bar, RUL, and agent reasoning mutually consistent: they all
        reflect what the monitoring system can actually see.
        """
        cfg = asset.config
        observed = asset.estimated_health
        if observed <= cfg.failure_threshold:
            asset.operating_state = AssetOperationalState.FAILED
        elif observed <= cfg.critical_threshold:
            asset.operating_state = AssetOperationalState.CRITICAL
        elif observed <= 60.0:
            asset.operating_state = AssetOperationalState.DEGRADED
        else:
            asset.operating_state = AssetOperationalState.NORMAL

    # -- simulation -------------------------------------------------------

    def tick(self) -> dict[str, TelemetryData]:
        """Advance the simulation by one tick.

        Returns:
            Mapping of asset id -> new telemetry reading.
        """
        self.tick_count += 1
        telemetry: dict[str, TelemetryData] = {}

        for asset_id, asset in self.assets.items():
            under_maintenance = asset.operating_state == AssetOperationalState.UNDER_MAINTENANCE
            if not under_maintenance:
                self._degrade(asset)

            reading = self._generate_telemetry(asset)
            telemetry[asset_id] = reading

            # State follows the freshly-estimated health (unless paused for a
            # physical maintenance intervention).
            if not under_maintenance:
                self._update_operating_state(asset)

            history = self.telemetry_history[asset_id]
            history.append(reading)
            if len(history) > self._history_limit:
                history.pop(0)

        return telemetry

    def _effective_degradation_rate(self, asset: AssetData) -> float:
        """Expected health loss per tick, including any active failure mode."""
        rate = asset.config.degradation_rate
        if asset.failure_mode in FAILURE_SIGNATURES:
            rate *= FAILURE_SIGNATURES[asset.failure_mode].degradation_multiplier
        return rate

    def _degrade(self, asset: AssetData) -> None:
        """Apply one tick of wear to latent ground-truth health."""
        # Load varies slightly around the asset's typical load; heavier load
        # wears faster.
        load_factor = 1.0 + float(self.rng.uniform(0.0, 0.10))
        loss = self._effective_degradation_rate(asset) * load_factor
        asset.true_health = max(0.0, asset.true_health - loss)
        asset.total_operating_hours += self.TICK_DURATION_SECONDS / 3600.0

    def _generate_telemetry(self, asset: AssetData) -> TelemetryData:
        """Generate sensor readings from ground-truth health + load + noise."""
        cfg = asset.config
        s = cfg.sensors
        now = datetime.now()

        stress = 1.0 - (asset.true_health / 100.0)  # 0 healthy .. 1 failed
        signature = FAILURE_SIGNATURES.get(asset.failure_mode or "")

        # Instantaneous load fraction (bounded), used for thermal/current terms.
        load_frac = float(np.clip(cfg.typical_load + self.rng.normal(0, 0.06), 0.2, 1.15))
        load_thermal = (load_frac - cfg.typical_load) * 12.0  # +/- C from load swing

        # Rare sensor spikes (transient events).
        spike_temp = 18.0 if self.rng.random() < 0.006 else 0.0
        spike_vib = 2.5 if self.rng.random() < 0.006 else 0.0

        temp_bias = signature.temp_bias if signature else 0.0
        vib_bias = signature.vibration_bias if signature else 0.0
        bearing_bias = signature.bearing_bias if signature else 0.0
        oil_bias = signature.oil_bias if signature else 0.0
        pf_bias = signature.power_factor_bias if signature else 0.0
        current_bias = signature.current_bias if signature else 0.0

        temperature = (
            _lerp(s.nominal_temp, s.failure_temp, stress)
            + load_thermal
            + temp_bias
            + float(self.rng.normal(0, s.temp_noise))
            + spike_temp
        )
        vibration = max(
            0.05,
            _lerp(s.nominal_vibration, s.failure_vibration, stress)
            + vib_bias
            + float(self.rng.normal(0, s.vibration_noise))
            + spike_vib,
        )
        bearing_wear = float(
            np.clip(stress * 80.0 + bearing_bias + self.rng.normal(0, 1.5), 0.0, 100.0)
        )
        oil_pressure = float(
            np.clip(
                _lerp(s.nominal_oil_pressure, s.failure_oil_pressure, stress)
                + oil_bias
                + self.rng.normal(0, 0.12),
                0.2,
                10.0,
            )
        )
        power_factor = float(
            np.clip(
                _lerp(s.nominal_power_factor, s.failure_power_factor, stress)
                + pf_bias
                + self.rng.normal(0, 0.008),
                0.5,
                1.0,
            )
        )
        voltage = s.nominal_voltage * (1.0 + float(self.rng.normal(0, 0.005)))
        current = (
            s.nominal_current
            * load_frac
            * (1.0 + current_bias)
            * (1.0 + float(self.rng.normal(0, 0.02)))
        )

        # Inverse mapping: estimate health from the sensor values (fusion).
        est_health = self._estimate_health(
            cfg, temperature, vibration, bearing_wear, oil_pressure, power_factor
        )
        # EMA smoothing for a stable displayed value.
        asset.estimated_health = (
            self._HEALTH_ESTIMATE_ALPHA * est_health
            + (1.0 - self._HEALTH_ESTIMATE_ALPHA) * asset.estimated_health
        )
        anomaly_score = float(np.clip(100.0 - asset.estimated_health, 0.0, 100.0))
        rul_hours = self._estimate_rul(asset)
        efficiency = float(np.clip(0.96 - stress * 0.22, 0.60, 0.99))

        return TelemetryData(
            timestamp=now,
            temperature=temperature,
            vibration=vibration,
            voltage=voltage,
            current=current,
            bearing_wear=bearing_wear,
            oil_pressure=oil_pressure,
            health_score=asset.estimated_health,
            power_factor=power_factor,
            rul_hours=rul_hours,
            anomaly_score=anomaly_score,
            load=load_frac * 100.0,
            efficiency=efficiency,
        )

    @staticmethod
    def _estimate_health(
        cfg: AssetConfig,
        temperature: float,
        vibration: float,
        bearing_wear: float,
        oil_pressure: float,
        power_factor: float,
    ) -> float:
        """Weighted sensor-fusion estimate of health from telemetry alone.

        Each indicator is normalised to a stress fraction in [0, 1.2] measuring
        how far it sits between its healthy and failed anchors; the weighted mean
        stress is inverted to a 0-100 health estimate.
        """
        s = cfg.sensors

        def stress_of(value: float, healthy: float, failed: float) -> float:
            span = failed - healthy
            if span == 0:
                return 0.0
            return float(np.clip((value - healthy) / span, 0.0, 1.2))

        temp_stress = stress_of(temperature, s.nominal_temp, s.failure_temp)
        vib_stress = stress_of(vibration, s.nominal_vibration, s.failure_vibration)
        bearing_stress = float(np.clip(bearing_wear / 80.0, 0.0, 1.2))
        # Oil & power factor degrade downward, so invert the anchors.
        oil_stress = stress_of(oil_pressure, s.nominal_oil_pressure, s.failure_oil_pressure)
        pf_stress = stress_of(power_factor, s.nominal_power_factor, s.failure_power_factor)

        fused = (
            temp_stress * 0.25
            + vib_stress * 0.30
            + bearing_stress * 0.20
            + oil_stress * 0.10
            + pf_stress * 0.15
        )
        return float(np.clip(100.0 * (1.0 - fused), 0.0, 100.0))

    def _estimate_rul(self, asset: AssetData) -> float:
        """Project remaining useful life (hours) from the current trajectory.

        Uses the smoothed health estimate and the expected per-tick degradation
        rate to extrapolate ticks-to-failure-threshold, then converts to hours.
        """
        rate = self._effective_degradation_rate(asset)
        headroom = asset.estimated_health - asset.config.failure_threshold
        if headroom <= 0:
            return 0.0
        if rate <= 1e-6:
            rate = 1e-6
        rul_ticks = headroom / rate
        return rul_ticks * self.TICK_DURATION_SECONDS / 3600.0

    # -- summary ----------------------------------------------------------

    def get_state_summary(self) -> dict:
        """Return a fleet-level state summary."""
        assets = []
        overall_health = 0.0
        min_rul = float("inf")
        for asset in self.assets.values():
            assets.append(asset.to_dict())
            overall_health += asset.estimated_health  # observed fleet health
            min_rul = min(min_rul, self._estimate_rul(asset))

        n = len(self.assets) or 1
        overall_health /= n
        uptime_hours = self.tick_count * self.TICK_DURATION_SECONDS / 3600.0

        return {
            "tick_count": self.tick_count,
            "uptime_hours": round(uptime_hours, 2),
            "overall_health": round(overall_health, 2),
            "min_rul_hours": round(min_rul, 1) if min_rul != float("inf") else None,
            "assets": assets,
        }
