"""
Digital-twin engine for industrial power-system assets.

The model keeps a single source of truth — each asset's ``health`` (0-100),
its true latent condition — and derives everything observable from it:

    ground-truth health  ->  physical sensor readings  ->  estimated health

1. **Degradation** lowers ground-truth health each tick (wear + any active
   failure mode).
2. **Telemetry** (temperature, vibration, bearing wear, oil pressure, power
   factor, voltage, current) is generated by interpolating between healthy and
   failed *sensor anchor points*, plus load, failure signatures, and noise.
3. **Health estimation** runs the inverse mapping — a weighted sensor-fusion
   estimate of health from the telemetry alone (what a real predictive model
   would see), smoothed with an EMA. A **Remaining Useful Life (RUL)** estimate
   in hours is projected from the current degradation trajectory.

This separation is deliberate: a digital twin knows the latent state, while the
predictive layer must *infer* it from sensors. It also makes the physics
testable — see ``tests/test_power_system.py``.

NOTE: All values are simulated. This is a demonstration model, not a validated
engineering simulation of real transformers/motors.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from enum import Enum

import numpy as np


class AssetType(Enum):
    """Types of power-system assets."""

    TRANSFORMER = "transformer"
    MOTOR = "motor"
    GENERATOR = "generator"
    PUMP = "pump"


class AssetOperationalState(Enum):
    """Operational states for assets."""

    NORMAL = "normal"
    DEGRADED = "degraded"
    CRITICAL = "critical"
    FAILED = "failed"
    UNDER_MAINTENANCE = "under_maintenance"


# ---------------------------------------------------------------------------
# Failure modes
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class FailureSignature:
    """How a developing fault biases sensors and accelerates degradation.

    A failure mode applies a one-off ``health_impact`` when injected and then
    persistently biases the named sensors and multiplies the wear rate until
    the asset is maintained.
    """

    label: str
    health_impact: float  # immediate one-off health loss (percent)
    degradation_multiplier: float  # ongoing wear-rate multiplier
    temp_bias: float = 0.0  # +C
    vibration_bias: float = 0.0  # +mm/s
    bearing_bias: float = 0.0  # +percentage points
    oil_bias: float = 0.0  # +bar (usually negative)
    power_factor_bias: float = 0.0
    current_bias: float = 0.0  # fractional, e.g. 0.2 = +20% current


