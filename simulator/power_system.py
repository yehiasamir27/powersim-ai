# ---------------------------------------------------------------------------
# Sensor / asset configuration
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SensorProfile:
    """Physical anchor points mapping health to sensor readings.

    Each sensor is defined at the healthy extreme (health=100) and the failed
    extreme (health=0); telemetry is interpolated between them.
    """

    nominal_temp: float
    failure_temp: float
    nominal_vibration: float
    failure_vibration: float
    nominal_oil_pressure: float
    failure_oil_pressure: float
    nominal_power_factor: float
    failure_power_factor: float
    nominal_voltage: float
    nominal_current: float
    temp_noise: float = 1.2
    vibration_noise: float = 0.15


@dataclass(frozen=True)
class AssetConfig:
    """Static configuration for a single asset."""

    asset_id: str
    asset_type: AssetType
    name: str
    rated_capacity: float  # kVA or kW
    sensors: SensorProfile
    normal_temp_range: tuple[float, float]
    normal_vibration_range: tuple[float, float]
    degradation_rate: float  # base health loss per tick (percent)
    critical_threshold: float
    failure_threshold: float
    typical_load: float = 0.7  # fraction of rated capacity in steady state


@dataclass
class TelemetryData:
    """A single set of sensor readings for an asset at one tick."""

    timestamp: datetime
    temperature: float  # Celsius
    vibration: float  # mm/s RMS
    voltage: float  # Volts
    current: float  # Amps
    bearing_wear: float  # 0-100 %
    oil_pressure: float  # bar
    health_score: float  # 0-100 %, sensor-estimated health (displayed)
    power_factor: float  # 0-1
    rul_hours: float  # estimated remaining useful life (hours)
    anomaly_score: float  # 0-100, higher = more anomalous
    load: float  # % of rated capacity
    efficiency: float  # 0-1

    def to_dict(self) -> dict:
        """Serialise telemetry for JSON transport."""
        return {
            "timestamp": self.timestamp.isoformat(),
            "temperature": round(float(self.temperature), 2),
            "vibration": round(float(self.vibration), 3),
            "voltage": round(float(self.voltage), 1),
            "current": round(float(self.current), 1),
            "bearing_wear": round(float(self.bearing_wear), 2),
            "oil_pressure": round(float(self.oil_pressure), 2),
            "health_score": round(float(self.health_score), 1),
            "power_factor": round(float(self.power_factor), 3),
            "rul_hours": round(float(self.rul_hours), 1),
            "anomaly_score": round(float(self.anomaly_score), 1),
            "load": round(float(self.load), 1),
            "efficiency": round(float(self.efficiency), 3),
        }


@dataclass
class AssetData:
    """Complete runtime state of a single asset.

    ``true_health`` is the latent ground-truth condition that drives the physics
    and is never directly observable in the real world. ``estimated_health`` is
    the EMA-smoothed sensor-fusion estimate — the value the product actually
    displays and reasons about, exactly as a real condition-monitoring system
    only ever *infers* condition from sensors.
    """

    config: AssetConfig
    true_health: float = 100.0  # latent ground truth (physics driver)
    estimated_health: float = 100.0  # observed estimate (displayed / reasoned on)
    operating_state: AssetOperationalState = AssetOperationalState.NORMAL
    total_operating_hours: float = 0.0
    last_maintenance: datetime | None = None
    failure_mode: str | None = None

    @property
    def health(self) -> float:
        """Backward-compatible alias for the observed (estimated) health."""
        return self.estimated_health

    def to_dict(self) -> dict:
        """Serialise asset state for JSON transport.

        ``health`` is the observed (sensor-estimated) value shown to users;
        ``true_health`` is exposed only for transparency/debugging and is clearly
        labelled as the simulator's latent ground truth.
        """
        return {
            "asset_id": self.config.asset_id,
            "asset_type": self.config.asset_type.value,
            "name": self.config.name,
            "health": round(self.estimated_health, 1),
            "true_health": round(self.true_health, 2),
            "operating_state": self.operating_state.value,
            "total_operating_hours": round(self.total_operating_hours, 2),
            "last_maintenance": self.last_maintenance.isoformat()
            if self.last_maintenance
            else None,
            "failure_mode": self.failure_mode,
            "failure_label": FAILURE_SIGNATURES[self.failure_mode].label
            if self.failure_mode in FAILURE_SIGNATURES
            else None,
        }


def _lerp(healthy: float, failed: float, stress: float) -> float:
    """Interpolate a sensor value given a stress fraction (0 healthy, 1 failed)."""
    return healthy + (failed - healthy) * stress


class PowerSystem:
    """Digital twin of an industrial power system with four assets."""

    # Each tick represents this many simulated minutes of operation. Chosen so
    # that Remaining-Useful-Life estimates read as realistic industrial horizons
    # (hundreds of hours) while the demo advances every couple of wall seconds.
    SIMULATED_MINUTES_PER_TICK: float = 15.0
    # Backwards-compatible alias (seconds of simulated time per tick).
    TICK_DURATION_SECONDS: float = SIMULATED_MINUTES_PER_TICK * 60.0

    # EMA smoothing factor for the health estimate (higher = more responsive).
    _HEALTH_ESTIMATE_ALPHA: float = 0.35

    def __init__(self, seed: int | None = None):
        """Initialise the digital twin.

        Args:
            seed: RNG seed for reproducible simulations.
        """
        self.rng = np.random.default_rng(seed)
        self.tick_count: int = 0
        self.start_time: datetime = datetime.now()
        self.assets: dict[str, AssetData] = {}
        self.telemetry_history: dict[str, list[TelemetryData]] = {}
        self._history_limit = 120
        self._initialize_assets()

